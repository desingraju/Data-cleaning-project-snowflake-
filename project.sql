SELECT * FROM FLIPKART;
BEGIN;
UPDATE FLIPKART
SET STATE =
CASE
    WHEN STATE = 'MH' THEN 'Maharashtra'
    WHEN STATE = 'KA' THEN 'Karnataka'
    WHEN STATE = 'TN' THEN 'Tamil Nadu'
    ELSE STATE
END;

COMMIT;
UPDATE FLIPKART
SET CITY =
CASE
    WHEN CITY = 'Hyd' THEN 'Hyderabad'
    WHEN CITY = 'Beng' THEN 'Bangalore'
    ELSE CITY
END;
UPDATE FLIPKART
SET GENDER =
CASE
    WHEN GENDER = 'M' THEN 'Male'
    WHEN GENDER = 'F' THEN 'Female'
    ELSE GENDER
END;
UPDATE FLIPKART
SET ORDER_ID = 'Unknown'
WHERE ORDER_ID IS NULL;
SELECT * FROM FLIPKART;